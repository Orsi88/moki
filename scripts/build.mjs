// Builds self-contained skills (and Claude Code subagents) from the canonical sources:
//   skills/<name>/**  +  core/*.md  ->  <mirror>/<name>/** (core under references/core/)
// for every mirror in MIRRORS. Mirrors are committed so a fresh clone works
// without running anything; `--check` fails when they drift from the source.
//
// Usage: node scripts/build.mjs [--check]

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, MIRRORS, listSkillDirs, walkFiles, relPosix } from './lib/repo.mjs';
import { claudeSubagent, hasUsableStatus, listAgents } from './lib/agents.ts';

// Built-in agents become native Claude Code subagents (usable ones only).
// claude-agents/*.md are copied unchanged into the same mirror (framework
// subagents that are not QA-activity agents).
const AGENT_MIRROR = '.claude/agents';
const CLAUDE_AGENTS = 'claude-agents';
const GENERATED = [...MIRRORS, AGENT_MIRROR];

const MIRROR_README = `# Generated folder — do not edit

This folder is generated by \`npm run build\` from \`skills/\` and \`core/\`.
Edit the canonical files there, then run \`npm run build\`.
It exists because each AI tool discovers skills in a different folder
(see docs/compatibility.md).
`;

export function expectedFiles(root = ROOT) {
  const files = new Map();
  const coreFiles = walkFiles(join(root, 'core')).filter((f) => f.endsWith('.md'));
  for (const mirror of MIRRORS) {
    files.set(`${mirror}/README.md`, Buffer.from(MIRROR_README));
    for (const skill of listSkillDirs(root)) {
      const skillDir = join(root, 'skills', skill);
      for (const file of walkFiles(skillDir)) {
        files.set(`${mirror}/${skill}/${relPosix(skillDir, file)}`, readFileSync(file));
      }
      for (const file of coreFiles) {
        files.set(`${mirror}/${skill}/references/core/${basename(file)}`, readFileSync(file));
      }
    }
  }
  for (const agent of listAgents(root).filter((a) => a.source === 'builtin' && hasUsableStatus(a))) {
    files.set(`${AGENT_MIRROR}/${agent.name}.md`, Buffer.from(claudeSubagent(agent)));
  }
  const extraDir = join(root, CLAUDE_AGENTS);
  if (existsSync(extraDir)) {
    for (const name of readdirSync(extraDir).filter((f) => f.endsWith('.md') && statSync(join(extraDir, f)).isFile())) {
      const path = `${AGENT_MIRROR}/${name}`;
      if (files.has(path)) throw new Error(`${CLAUDE_AGENTS}/${name} collides with a built-in agent`);
      files.set(path, readFileSync(join(extraDir, name)));
    }
  }
  return files;
}

export function findDrift(root = ROOT) {
  const expected = expectedFiles(root);
  const problems = [];
  const actual = new Set();
  for (const mirror of GENERATED) {
    for (const file of walkFiles(join(root, mirror))) actual.add(relPosix(root, file));
  }
  for (const [path, content] of expected) {
    const full = join(root, path);
    if (!existsSync(full)) problems.push(`missing: ${path}`);
    else if (!readFileSync(full).equals(content)) problems.push(`outdated: ${path}`);
  }
  for (const path of actual) {
    if (!expected.has(path)) problems.push(`unexpected: ${path}`);
  }
  return problems;
}

export function build(root = ROOT) {
  const files = expectedFiles(root);
  for (const mirror of GENERATED) rmSync(join(root, mirror), { recursive: true, force: true });
  for (const [path, content] of files) {
    const full = join(root, path);
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, content);
  }
  return files.size;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  if (process.argv.includes('--check')) {
    const drift = findDrift();
    if (drift.length) {
      console.error('Generated skill mirrors are out of date. Run `npm run build`.');
      drift.forEach((d) => console.error(`  ${d}`));
      process.exit(1);
    }
    console.log('Skill and agent mirrors are up to date.');
  } else {
    const count = build();
    console.log(`Built ${count} files into ${GENERATED.join(", ")}.`);
  }
}
